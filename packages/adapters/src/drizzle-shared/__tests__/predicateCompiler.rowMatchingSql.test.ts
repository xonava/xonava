const maps: Record<PredicateDialect, Record<string, AnyColumn>> = {
  postgres: { ...(pgT as unknown as Record<string, AnyColumn>), ...fakes(pgT.s) },
  mysql: { ...(myT as unknown as Record<string, AnyColumn>), ...fakes(myT.s) },
  sqlite: { ...(liteT as unknown as Record<string, AnyColumn>), ...fakes(liteT.s) },
  generic: { ...(liteT as unknown as Record<string, AnyColumn>), ...fakes(liteT.s) },
}
const render = (dialect: PredicateDialect, node: PredicateNode, options: PredicateCompilerOptions = {}) => {
  const query = dialects[dialect].sqlToQuery(new DrizzlePredicateCompiler(maps[dialect], { dialect, ...options }).compile(node) as SQL)
  return { sql: query.sql, params: query.params }
}

type Spec = () => PredicateNode
const describeNode = (node: PredicateNode): string => JSON.stringify(node, (_key, value: unknown) => typeof value === "number" && Number.isNaN(value) ? "NaN" : value instanceof Date ? `Date(${Number.isNaN(value.getTime()) ? "invalid" : value.toISOString()})` : value === undefined ? "undefined" : value)
const run = (dialect: PredicateDialect, specs: readonly Spec[], options: PredicateCompilerOptions = {}) => {
  const results: Record<string, unknown> = {}
  for (const spec of specs) {
    const node = spec()
    try { results[describeNode(node)] = render(dialect, node, options) } catch (error) { results[describeNode(node)] = `THROW ${(error as Error).message}` }
  }
  return results
}

