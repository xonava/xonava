/** A copy of a real column whose classification inputs are replaced (what the compiler reads: dataType, columnType, getSQLType). */
function fake(base: AnyColumn, overrides: { dataType?: string; sqlType?: string | null; columnType?: string }): AnyColumn {
  const copy = Object.assign(Object.create(Object.getPrototypeOf(base) as object) as object, base) as Record<string, unknown>
  if (overrides.dataType !== undefined) copy.dataType = overrides.dataType
  if (overrides.columnType !== undefined) copy.columnType = overrides.columnType
  if (overrides.sqlType === null) copy.getSQLType = undefined
  else if (overrides.sqlType !== undefined) copy.getSQLType = () => overrides.sqlType
  return copy as unknown as AnyColumn
}
